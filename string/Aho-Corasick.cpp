/* Trie 木： 文字の種類(char_size)、int型で0に対応する文字(base)
    insert(word): 単語 word を Trie 木に挿入する
    search(word): 単語 word が Trie 木にあるか判定する
    start_with(prefix):  prefix が一致する単語が Trie 木にあるか判定する
    count(): 挿入した単語の数を返す
    size(): Trie 木の頂点数を返す
    計算量：insert, search ともに O(M)（Mは単語の長さ）
*/
template <int char_size, int base>
struct Trie {
    struct Node {            // 頂点を表す構造体
        array<int, char_size> next;    // 子の頂点番号を格納。存在しなければ-1
        // vector<int> next;
        vector<int> accept;  // 末端がこの頂点になる単語の word_id を保存
        int c;               // base からの間隔をint型で表現したもの
        int common;          // いくつの単語がこの頂点を共有しているか
        Node(int c_) : c(c_), common(0) {
            next.fill(-1);
            // next.assign(char_size, -1);
        }
    };

    vector<Node> nodes;  // trie 木本体
    int root;
    Trie() : root(0) {
        nodes.push_back(Node(root));
    }

    // 単語の挿入
    int insert(const string& word, int word_id) {
        int node_id = 0;
        for (int i = 0; i < (int)word.size(); i++) {
            int c = (int)(word[i] - base);
            if (nodes[node_id].next[c] == -1) {  // 次の頂点が存在しなければ追加
                nodes[node_id].next[c] = (int)nodes.size();
                nodes.push_back(Node(c));
            }
            ++nodes[node_id].common;
            node_id = nodes[node_id].next[c];
        }
        ++nodes[node_id].common;
        nodes[node_id].accept.push_back(word_id);
        return node_id;
    }
    int insert(const string &word) {
        return insert(word, nodes[0].common);
    }

    // 単語とprefixの検索
    bool search(const string& word, bool prefix = false) {
        int node_id = 0;
        for (int i = 0; i < (int)word.size(); i++) {
            int c = (int)(word[i] - base);
            int next_id = nodes[node_id].next[c];
            if (next_id == -1) {  // 次の頂点が存在しなければ終了
                return false;
            }
            node_id = next_id;
        }
        return (prefix) ? true : nodes[node_id].accept.size() > 0;
    }

    // prefix を持つ単語が存在するかの検索
    bool start_with(const string& prefix) {
        return search(prefix, true);
    }

    // 挿入した単語の数
    int count() const {
        return (nodes[0].common);
    }
    // Trie木のノード数
    int size() const {
        return ((int)nodes.size());
    }
};

template <int char_size, int base>
struct AhoCorasick : Trie<char_size, base> {
    using Trie<char_size, base>::nodes;
    vector<int> fail;
    vector<int> bfs_order;

    // trie を BFS order で辿る
    // failure link を作成
    void build() {
        fail.assign(nodes.size(), -1);
        queue<int> q;
        q.push(0);
        bfs_order.pb(0);
        while(q.size()) {
            int u = q.front(); q.pop();
            bfs_order.pb(u);
            for(int i = 0; i < char_size; i++) {
                int v = nodes[u].next.at(i);
                if(v == -1) continue;
                fail[v] = move(fail[u], (char)(base + i));
                q.push(v);
            }
        }
        reverse(ALL(bfs_order));
    }

    // trie の状態 cur から次に ch を読んだ時にどこへ行くか求める
    // <cur> ->(failure) ... ->(failure) =>(trie) <result>
    int move(int cur, char ch){
        int c = (int)(ch - base);
        while(cur != -1) {
            int nxt = nodes[cur].next[c];
            if(nxt != -1) return nxt;
            cur = fail[cur];
        }
        return 0;
    }
};

